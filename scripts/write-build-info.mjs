#!/usr/bin/env node
/**
 * Bake the release channel into src/build-info.generated.ts before tsc.
 *
 *   CANONICAL_BUILD_CHANNEL=staging|production node scripts/write-build-info.mjs
 *
 * Default channel is staging (local/dev and @staging publishes). Production
 * CI sets CANONICAL_BUILD_CHANNEL=production so api.deft.co is hardcoded into
 * that tarball. Endpoints are not customer-switchable at runtime.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "src", "build-info.generated.ts");

const CHANNELS = {
  staging: {
    channel: "staging",
    collectionBaseUrl: "https://api.deft-staging.co/collector",
    collectionEnv: "staging",
  },
  production: {
    channel: "production",
    collectionBaseUrl: "https://api.deft.co/collector",
    collectionEnv: "production",
  },
};

const raw = (process.env.CANONICAL_BUILD_CHANNEL ?? "staging").trim().toLowerCase();
const selected = CHANNELS[raw];
if (selected === undefined) {
  console.error(
    `write-build-info: invalid CANONICAL_BUILD_CHANNEL=${JSON.stringify(raw)} ` +
      `(expected staging|production)`,
  );
  process.exit(2);
}

const body = `/* AUTO-GENERATED by scripts/write-build-info.mjs — do not edit by hand. */
export type BuildChannel = "staging" | "production";

export const BUILD_CHANNEL: BuildChannel = ${JSON.stringify(selected.channel)};
export const COLLECTION_BASE_URL: string = ${JSON.stringify(selected.collectionBaseUrl)};
export const COLLECTION_ENV: string = ${JSON.stringify(selected.collectionEnv)};
`;

writeFileSync(outPath, body, "utf8");
console.log(
  `write-build-info: channel=${selected.channel} url=${selected.collectionBaseUrl} → ${outPath}`,
);
